let currentLanguage = 0;

export function setLanguage(langCode) {
    currentLanguage = Number(langCode);
    if (!translations[currentLanguage]) {
        currentLanguage = 0;
    }
    localStorage.setItem("melting_language", currentLanguage);
    applyTranslations();
}

export function getLanguage() {
    const saved = localStorage.getItem("melting_language");
    if (saved !== null) {
        currentLanguage = Number(saved);
    }
    return currentLanguage;
}

export function t(key) {
    const lang = translations[currentLanguage] || translations[0];
    return lang[key] !== undefined ? lang[key] : (translations[0][key] || key);
}

export function applyTranslations() {
    document.querySelectorAll("[data-i18n]").forEach(elem => {
        const key = elem.getAttribute("data-i18n");
        const translation = t(key);
        if (translation !== undefined) {
            if (elem.tagName === "INPUT" || elem.tagName === "TEXTAREA") {
                if (elem.hasAttribute("placeholder")) {
                    elem.setAttribute("placeholder", translation);
                }
            } else {
                elem.textContent = translation;
            }
        }
    });

    document.querySelectorAll("[data-i18n-title]").forEach(elem => {
        const key = elem.getAttribute("data-i18n-title");
        const translation = t(key);
        if (translation !== undefined) {
            elem.setAttribute("title", translation);
        }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(elem => {
        const key = elem.getAttribute("data-i18n-placeholder");
        const translation = t(key);
        if (translation !== undefined) {
            elem.setAttribute("placeholder", translation);
        }
    });
}
